begin;

create extension if not exists pgcrypto;

create table public.app_users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  system_role text not null default 'user'
    check (system_role in ('user', 'admin')),
  membership_tier text not null default 'guest'
    check (membership_tier in ('guest', 'member')),
  status text not null default 'active'
    check (status in ('active', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.trial_entitlements (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.app_users(id) on delete cascade,
  trial_claimed_at timestamptz not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  check (expires_at = trial_claimed_at + interval '7 days')
);

create table public.open_ids (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.app_users(id) on delete cascade,
  open_id text not null unique,
  kind text not null check (kind in ('trial', 'paid')),
  is_exportable boolean not null default false,
  status text not null default 'active'
    check (status in ('active', 'revoked')),
  expires_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  unique (id, user_id),
  check (
    (kind = 'trial' and is_exportable = false and expires_at is not null)
    or
    (kind = 'paid' and is_exportable = true)
  )
);

create unique index one_trial_open_id_per_user
  on public.open_ids(user_id)
  where kind = 'trial';

create unique index one_paid_open_id_per_user
  on public.open_ids(user_id)
  where kind = 'paid';

create table public.gateway_credentials (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.app_users(id) on delete cascade,
  open_id_id uuid not null,
  label text,
  token_hash text not null unique,
  token_prefix text not null,
  expires_at timestamptz,
  revoked_at timestamptz,
  last_used_at timestamptz,
  created_at timestamptz not null default now(),
  foreign key (open_id_id, user_id)
    references public.open_ids(id, user_id)
    on delete cascade
);

create index gateway_credentials_user_created_idx
  on public.gateway_credentials(user_id, created_at desc);
create index gateway_credentials_open_id_idx
  on public.gateway_credentials(open_id_id);

create table public.mcp_connections (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.app_users(id) on delete cascade,
  provider text not null,
  status text not null default 'connected'
    check (status in ('connected', 'invalid', 'unavailable')),
  credential_ciphertext text not null,
  credential_version integer not null default 1,
  last_verified_at timestamptz,
  last_error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, provider)
);

create index mcp_connections_user_idx
  on public.mcp_connections(user_id);

create table public.gateway_audit_events (
  id bigint generated by default as identity primary key,
  user_id uuid references public.app_users(id) on delete set null,
  credential_id uuid references public.gateway_credentials(id) on delete set null,
  event_type text not null,
  provider text,
  operation text,
  success boolean,
  error_code text,
  duration_ms integer,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index gateway_audit_user_created_idx
  on public.gateway_audit_events(user_id, created_at desc);
create index gateway_audit_type_created_idx
  on public.gateway_audit_events(event_type, created_at desc);

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.app_users (id, email, display_name)
  values (
    new.id,
    new.email,
    nullif(coalesce(new.raw_user_meta_data ->> 'display_name', ''), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

create or replace function public.claim_gateway_trial(
  p_user_id uuid,
  p_open_id text,
  p_token_hash text,
  p_token_prefix text
)
returns table (
  open_id_row_id uuid,
  credential_id uuid,
  trial_expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_claimed_at timestamptz := now();
  v_expires_at timestamptz := v_claimed_at + interval '7 days';
  v_open_id_id uuid;
  v_credential_id uuid;
  v_membership text;
  v_status text;
begin
  select membership_tier, status
  into v_membership, v_status
  from public.app_users
  where id = p_user_id
  for update;

  if not found or v_status <> 'active' then
    raise exception 'ACCOUNT_NOT_ACTIVE';
  end if;

  if v_membership <> 'guest' then
    raise exception 'TRIAL_GUEST_ONLY';
  end if;

  insert into public.trial_entitlements (
    user_id,
    trial_claimed_at,
    expires_at
  )
  values (
    p_user_id,
    v_claimed_at,
    v_expires_at
  );

  insert into public.open_ids (
    user_id,
    open_id,
    kind,
    is_exportable,
    expires_at
  )
  values (
    p_user_id,
    p_open_id,
    'trial',
    false,
    v_expires_at
  )
  returning id into v_open_id_id;

  insert into public.gateway_credentials (
    user_id,
    open_id_id,
    label,
    token_hash,
    token_prefix,
    expires_at
  )
  values (
    p_user_id,
    v_open_id_id,
    '7-day trial',
    p_token_hash,
    p_token_prefix,
    v_expires_at
  )
  returning id into v_credential_id;

  return query
  select v_open_id_id, v_credential_id, v_expires_at;
exception
  when unique_violation then
    raise exception 'TRIAL_ALREADY_USED';
end;
$$;

alter table public.app_users enable row level security;
alter table public.trial_entitlements enable row level security;
alter table public.open_ids enable row level security;
alter table public.gateway_credentials enable row level security;
alter table public.mcp_connections enable row level security;
alter table public.gateway_audit_events enable row level security;

revoke all on table public.trial_entitlements from anon, authenticated;
revoke all on table public.open_ids from anon, authenticated;
revoke all on table public.gateway_credentials from anon, authenticated;
revoke all on table public.mcp_connections from anon, authenticated;
revoke all on table public.gateway_audit_events from anon, authenticated;
revoke execute on function public.claim_gateway_trial(uuid, text, text, text)
  from public, anon, authenticated;
grant execute on function public.claim_gateway_trial(uuid, text, text, text)
  to service_role;

grant all on table public.app_users to service_role;
grant all on table public.trial_entitlements to service_role;
grant all on table public.open_ids to service_role;
grant all on table public.gateway_credentials to service_role;
grant all on table public.mcp_connections to service_role;
grant all on table public.gateway_audit_events to service_role;
grant usage, select on sequence public.gateway_audit_events_id_seq to service_role;

commit;
